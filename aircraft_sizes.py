LIGHT = {t for t, (span, _) in SIZES.items() if span < 13.5} - HELICOPTERS


def category_for(icao_type: str | None, category: str | None) -> str | None:
    """The ADS-B category, inferred from the type when the feed doesn't send one."""
    if category:
        return category
    t = (icao_type or "").upper()
    if t in HELICOPTERS:
        return "A7"
    if t in LIGHT:
        return "A1"
    return None


def size_for(icao_type: str | None, category: str | None) -> tuple[float, float]:
    if icao_type and icao_type.upper() in SIZES:
        return SIZES[icao_type.upper()]
    if category and category.upper() in CATEGORY_SIZES:
        return CATEGORY_SIZES[category.upper()]
    return DEFAULT_SIZE
